import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const output = `// Generated by scripts/generate-types.mjs. Do not edit directly.
export type EndpointConfig = { type: "local"; path: string };
export interface GroupRule { label: string; pattern: string }
export interface RenameRule { pattern: string; destination: string }
export type SelectionMode = "manual" | "groups";
export type TriggerConfig =
  | { type: "manual" }
  | { type: "watch"; debounceMs: number }
  | { type: "interval"; seconds: number }
  | { type: "cron"; expression: string; timezone?: string };

export interface CopyRule {
  schemaVersion: 1;
  id: string;
  name: string;
  enabled: boolean;
  source: EndpointConfig;
  destination: EndpointConfig;
  filters: {
    include: string[];
    exclude: string[];
    includeHidden: boolean;
    group: GroupRule | null;
    selectedGroups: string[];
    autoLatestGroup: boolean;
    singleGroup: boolean;
    confirmGroupsBeforeRun: boolean;
    selectionMode: SelectionMode;
  };
  copy: {
    mode: "incremental";
    compare: "size-and-mtime" | "size-only";
    overwrite: "if-changed" | "never" | "always";
    symlinks: "skip";
    preserveMtime: boolean;
    maxConcurrency: number;
    retryCount: number;
    rename: RenameRule | null;
  };
  trigger: TriggerConfig;
}

export interface PlanStats {
  directoriesToCreate: number;
  filesToCopy: number;
  filesToSkip: number;
  warnings: number;
  bytesToCopy: number;
}

export type PlanAction = "create-directory" | "copy-file" | "skip" | "warn";
export interface PlanItem {
  action: PlanAction;
  relativePath: string;
  destinationPath?: string;
  warning?: string;
  size: number;
  reason: string;
}
export interface CopyPlan { ruleId: string; items: PlanItem[]; stats: PlanStats }
export interface PlanProgressEvent {
  phase: "scanning" | "planning";
  completedEntries: number;
  totalEntries: number | null;
  relativePath: string | null;
}
export interface JobSummary {
  jobId: string; ruleId: string; startedAt: string; finishedAt: string;
  status: "succeeded" | "partial" | "failed" | "cancelled";
  copiedFiles: number; skippedFiles: number; failedFiles: number; copiedBytes: number;
  errors: Array<{ relativePath: string; message: string }>;
}
export interface ProgressEvent {
  jobId: string; relativePath: string; completedFiles: number; totalFiles: number;
  copiedBytes: number; totalBytes: number;
}
export interface JobEvent {
  timestamp: string; level: string; phase: string; relativePath?: string;
  operation: string; result: string; message?: string;
}
export interface SourceEntry {
  relativePath: string;
  directory: boolean;
  size: number;
  modified: number | null;
}
export interface RecentPaths {
  schemaVersion: 1;
  sources: string[];
  destinations: string[];
  locale: "en" | "zh";
}
`;

const target = fileURLToPath(new URL("../src/types/generated.ts", import.meta.url));
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) {
    console.error("Generated TypeScript contracts are stale. Run npm run generate:types.");
    process.exitCode = 1;
  }
} else {
  writeFileSync(target, output, "utf8");
}
